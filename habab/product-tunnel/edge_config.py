#!/usr/bin/env python3
"""Render the public-edge HTTP-01 and exact-host TLS vhost for one home."""

from __future__ import annotations

import argparse
import sys

from manage_home import HOST_SUFFIX, ID_RE

BACKEND = "95.217.227.164:80"
WEBROOT = "/var/www/habab.ru"
CERT_ROOT = "/etc/letsencrypt/live"


class EdgeConfigError(ValueError):
    pass


def render(home_id: str, port: int) -> tuple[str, str]:
    """Return an exact-host edge vhost pair and its canonical product hostname.

    The edge proxy points to the existing VM104 HTTP ingress. That ingress is
    generated by manage_home.render() and routes this exact Host header to the
    matching loopback reverse-forward port.
    """
    if not isinstance(home_id, str) or not ID_RE.fullmatch(home_id):
        raise EdgeConfigError("home id must be 1-32 lowercase letters, digits, or internal hyphens")
    if isinstance(port, bool) or not isinstance(port, int) or not 32000 <= port <= 39999:
        raise EdgeConfigError("loopback port must be in 32000-39999")

    host = f"home-{home_id}{HOST_SUFFIX}"
    certificate = f"{CERT_ROOT}/{host}"
    config = f"""# Staged for {home_id}; paired VM104 backend loopback port {port}.
# Do not install until DNS and certificate are verified.
server {{
    listen 80;
    server_name {host};
    if ($host != {host}) {{ return 444; }}

    location ^~ /.well-known/acme-challenge/ {{
        root {WEBROOT};
        default_type text/plain;
        try_files $uri =404;
    }}

    location / {{ return 301 https://$host$request_uri; }}
}}

server {{
    listen 443 ssl;
    server_name {host};
    if ($host != {host}) {{ return 444; }}

    ssl_certificate {certificate}/fullchain.pem;
    ssl_certificate_key {certificate}/privkey.pem;

    location / {{
        proxy_pass http://{BACKEND};
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_read_timeout 3600s;
        proxy_buffering off;
    }}
}}
"""
    return host, config


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--home-id", required=True)
    parser.add_argument("--port", required=True, type=int, help="assigned relay loopback port")
    args = parser.parse_args()
    try:
        _, config = render(args.home_id, args.port)
    except EdgeConfigError as err:
        print(f"error: {err}", file=sys.stderr)
        return 2
    sys.stdout.write(config)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
